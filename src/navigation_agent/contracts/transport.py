"""现有控制台的通信边界；业务模块不依赖 aiohttp 或 WebSocket。"""

from collections.abc import Callable
from typing import Any, Protocol


class ControlChannel(Protocol):
    state: dict[str, Any]
    error: Exception | None
    on_snapshot: Callable[[], None]

    async def __aenter__(self): ...
    async def __aexit__(self, exc_type, exc, traceback): ...
    async def command(self, kind: str, **parameters) -> None: ...
    async def send(self, payload: dict) -> None: ...
    async def wait_snapshot(self) -> None: ...
    async def camera(self) -> bytes: ...
    def diagnostics(self, action: str) -> dict: ...

